// Bundles src/elements/auto.ts into assets/osqd-ui-elements.js: one minified script a plain HTML
// page can load with <script src>, which defines every element and exposes the API as window.OQ.
// `--check` fails instead of writing when the committed file is out of date (run by `npm run check`).
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const root = new URL("../", import.meta.url);
const result = await build({
  entryPoints: [fileURLToPath(new URL("src/elements/auto.ts", root))],
  bundle: true,
  format: "iife",
  globalName: "OQ",
  minify: true,
  target: "es2020",
  legalComments: "none",
  write: false,
  banner: { js: "/* @osqd/ui custom elements. GENERATED by scripts/elements.mjs — do not edit. */" },
});
const out = result.outputFiles[0].text;

// The dashboards that embed these elements (bothandlerjs, hackerpot, admin-panel-builder) bundle
// them into one nonced <script> and refuse the same things their own client builds refuse:
// markup-string sinks, code from strings, and sequences that end a <script> element early or open
// an HTML comment. Checked in the sources as written — comments included, since a consumer may
// bundle them unminified — and in the bundle. tests/elements.test.ts asserts the same.
const FORBIDDEN = ["innerHTML", "outerHTML", "insertAdjacentHTML", "document.write", "eval(", "new Function", "</script", "<!--", "-->"];
const srcDir = new URL("src/elements/", root);
const offences = [];
for (const name of readdirSync(srcDir)) {
  const text = readFileSync(new URL(name, srcDir), "utf8");
  for (const f of FORBIDDEN) if (text.includes(f)) offences.push(`src/elements/${name} contains ${JSON.stringify(f)}`);
}
for (const f of FORBIDDEN) if (out.includes(f)) offences.push(`the bundle contains ${JSON.stringify(f)}`);
if (offences.length) {
  console.error(`${offences.join("\n")}\nBuild DOM with createElement and textContent instead; see src/elements/base.ts.`);
  process.exit(1);
}
const file = fileURLToPath(new URL("assets/osqd-ui-elements.js", root));

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(file, "utf8");
  } catch {}
  if (current !== out) {
    console.error("assets/osqd-ui-elements.js is out of date — run `npm run elements`.");
    process.exit(1);
  }
  console.log("assets/osqd-ui-elements.js is up to date.");
} else {
  writeFileSync(file, out);
  console.log(`wrote assets/osqd-ui-elements.js (${(out.length / 1024).toFixed(1)} KB)`);
}
