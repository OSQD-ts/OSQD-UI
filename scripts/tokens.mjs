// Writes styles/tokens.css from src/theme/index.ts — the themes are the source of truth.
// `--check` fails instead of writing when the file on disk is out of date (run by `npm run check`).
// The theme module has no imports, so esbuild strips its types and it loads as a data: URL.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { transform } from "esbuild";

const root = new URL("../", import.meta.url);
const source = readFileSync(new URL("src/theme/index.ts", root), "utf8");
const { code } = await transform(source, { loader: "ts", format: "esm" });
const { darkTheme, lightTheme, themes, themeToCss } = await import(`data:text/javascript,${encodeURIComponent(code)}`);
const variants = Object.values(themes).filter((t) => t !== darkTheme && t !== lightTheme);

// Every rule also has a `:host(...)` twin, so the same stylesheet themes a shadow root: inside
// one, `:root` and `[data-theme]` cannot see the host element, while `:host` can.
const scope = (name) => `[data-theme="${name}"],\n:host([data-theme="${name}"])`;
const indent = (css) =>
  css
    .split("\n")
    .map((l) => (l ? `  ${l}` : l))
    .join("\n")
    .trimEnd();

const out = [
  "/* GENERATED by scripts/tokens.mjs from src/theme/index.ts — do not edit by hand. */",
  "",
  "/* Dark is the default — on the page, and on a shadow host — and data-theme switches any subtree. */",
  themeToCss(darkTheme, `:root,\n:host,\n${scope("dark")}`),
  themeToCss(lightTheme, scope("light")),
  "/* data-theme=\"auto\" follows the operating system. */",
  "@media (prefers-color-scheme: light) {",
  indent(themeToCss(lightTheme, scope("auto"))),
  "}",
  "",
  "/* Variants. */",
  ...variants.map((t) => themeToCss(t, scope(t.name))),
].join("\n");

const file = fileURLToPath(new URL("styles/tokens.css", root));
if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(file, "utf8");
  } catch {}
  if (current !== out) {
    console.error("styles/tokens.css is out of date — run `npm run tokens`.");
    process.exit(1);
  }
  console.log("styles/tokens.css is up to date.");
} else {
  writeFileSync(file, out);
  console.log("wrote styles/tokens.css");
}
