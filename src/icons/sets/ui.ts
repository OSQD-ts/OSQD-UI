/** A five-point star centred on (cx, cy) with outer radius R. */
const star = (cx: number, cy: number, R: number) => {
  const pts: string[] = [];
  for (let i = 0; i < 10; i++) {
    const rad = i % 2 === 0 ? R : R * 0.45;
    const a = -Math.PI / 2 + (i * Math.PI) / 5;
    pts.push(`${fmt(cx + rad * Math.cos(a))},${fmt(cy + rad * Math.sin(a))}`);
  }
  return pg(pts.join(" "));
};

