/** A toothed gear as one polygon plus its hub. */
const gear = (cx: number, cy: number, ro: number, ri: number, teeth = 8, hub = 0) => {
  const pts: string[] = [];
  const step = (2 * Math.PI) / teeth;
  for (let k = 0; k < teeth; k++) {
    const a = k * step;
    for (const [d, rad] of [
      [-0.3, ri],
      [-0.17, ro],
      [0.17, ro],
      [0.3, ri],
    ] as const) {
      const t = a + d * step * 1.6;
      pts.push(`${n2(cx + rad * Math.cos(t))},${n2(cy + rad * Math.sin(t))}`);
    }
  }
  return pg(pts.join(" ")) + (hub ? c(cx, cy, hub) : "");
};

/** A regular hexagon, pointy top. */
const hex = (cx: number, cy: number, rad: number) => {
  const pts: string[] = [];
  for (let k = 0; k < 6; k++) {
    const t = -Math.PI / 2 + (k * Math.PI) / 3;
    pts.push(`${n2(cx + rad * Math.cos(t))},${n2(cy + rad * Math.sin(t))}`);
  }
  return pg(pts.join(" "));
};

