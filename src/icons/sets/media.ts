// Six blades: a line from each vertex of an inner hexagon, along the next edge, out to the rim.
function aperture(): string {
  let out = c(12, 12, 9);
  for (let i = 0; i < 6; i++) {
    const a = (i * Math.PI) / 3;
    const b = ((i + 1) * Math.PI) / 3;
    const vx = 12 + 4 * Math.cos(a);
    const vy = 12 + 4 * Math.sin(a);
    const dx = 4 * Math.cos(a) - 4 * Math.cos(b);
    const dy = 4 * Math.sin(a) - 4 * Math.sin(b);
    const len = Math.hypot(dx, dy);
    const ux = dx / len;
    const uy = dy / len;
    // Solve |v + t·u − centre| = 9 for t > 0.
    const ox = vx - 12;
    const oy = vy - 12;
    const bq = 2 * (ox * ux + oy * uy);
    const cq = ox * ox + oy * oy - 81;
    const t = (-bq + Math.sqrt(bq * bq - 4 * cq)) / 2;
    out += l(n2(vx), n2(vy), n2(vx + t * ux), n2(vy + t * uy));
  }
  return out;
}

function colorWheel(): string {
  let out = c(12, 12, 9) + c(12, 12, 3);
  for (let i = 0; i < 6; i++) {
    const a = (i * Math.PI) / 3 + Math.PI / 6;
    out += l(n2(12 + 3 * Math.cos(a)), n2(12 + 3 * Math.sin(a)), n2(12 + 9 * Math.cos(a)), n2(12 + 9 * Math.sin(a)));
  }
  return out;
}

/** A dashed square, from short strokes, for selection marquees. */
function dashedSquare(lo: number, hi: number): string {
  const seg = [lo, lo + 3.5, (lo + hi) / 2 - 1.5, (lo + hi) / 2 + 1.5, hi - 3.5, hi];
  let out = "";
  for (let i = 0; i < seg.length; i += 2) {
    out += l(seg[i] as number, lo, seg[i + 1] as number, lo) + l(seg[i] as number, hi, seg[i + 1] as number, hi);
    out += l(lo, seg[i] as number, lo, seg[i + 1] as number) + l(hi, seg[i] as number, hi, seg[i + 1] as number);
  }
  return out;
}

